export type TaskStatus = 'pending' | 'done';

// 005-habitos-tareas-metas-ux: same vocabulary as HabitScheduleMode, but a
// field of its own — Task and Habit remain separate domain concepts
// (Principio XIII) and never share a recurrence table.
export type TaskScheduleMode = 'fixed_days' | 'frequency';

export interface Task extends BaseEntity {
  id: UUID;
  user_id: UUID;
  title: string;
  due_date: Date;
  status: TaskStatus;
  done_at?: Date;
  description?: string; // NUEVO (005-habitos-tareas-metas-ux, FR-007) — nota opcional
  // 005-habitos-tareas-metas-ux (FR-001/FR-003/FR-004/FR-005): a Task is
  // recurrent if and only if it has schedule_mode (and therefore
  // recurrence_series_id) set. Each generated occurrence is its own
  // independent Task row — never a streak or a token (Principio XIII).
  schedule_mode?: TaskScheduleMode;
  fixed_days?: DayOfWeek[]; // required if schedule_mode = 'fixed_days', at least one
  frequency_target?: number; // required if schedule_mode = 'frequency', >= 1
  recurrence_series_id?: UUID; // groups every occurrence generated from the same recurring Task
  recurrence_active?: boolean; // false = stop generating future occurrences (FR-004); only meaningful on the most recent occurrence of a series
}

export type DebtDirection = 'lent' | 'borrowed';
export type DebtOrigin = 'manual' | 'shared_expense';

export interface Debt extends BaseEntity {
  id: UUID;
  user_id: UUID;
  counterparty_name: string;
  direction: DebtDirection;
  origin: DebtOrigin;
  shared_movement_id?: UUID; // set once origin === 'shared_expense' (family-space feature, not yet implemented)
  amount: number; // in cents
  settled_amount: number; // in cents; accumulates partial repayments, never exceeds `amount`
  due_date?: Date;
  interest_rate?: number; // informational only (spec.md Assumptions) — never recalculated
}

// InstallmentLoan/InstallmentPayment (spec 002, US3) — a separate entity from
// Debt on purpose (research.md #3): bank/caja loans with a lender-defined
// installment schedule. The app never computes an amortization table — every
// number (amount, installment_count, installment_amount) comes verbatim from
// the user, who copies it from their lender (FR-011, FR-012).
export type InstallmentLoanStatus = 'active' | 'settled';
export type InstallmentPaymentKind = 'installment' | 'principal';
export type InstallmentAdjustmentType = 'reduce_term' | 'reduce_installment_amount';

export interface InstallmentLoan extends BaseEntity {
  id: UUID;
  user_id: UUID;
  lender_name: string;
  amount: number; // in cents, total originally borrowed (FR-011)
  installment_count: number; // originally pactado, never changes on its own
  remaining_installments: number; // 0 <= remaining_installments <= installment_count
  installment_amount: number; // in cents, current — can change via a principal payment (FR-016/FR-017)
  interest_rate?: number; // optional, purely informational, never used to calculate anything (FR-013)
  status: InstallmentLoanStatus; // derived: 'settled' once remaining_installments = 0 (FR-025), never reverts
  distribution_category_id?: UUID; // spec 003 FR-010/FR-011 — bucket used by the Movement this loan's payments generate
}

// Append-only payment log (FR-026) — analogous to HabitCompletion. Recording
// one is bookkeeping (fecha, tipo, cuotas restantes); UNLIKE Debt/
// applyDebtSettlement, recording one now ALSO generates a real expense
// Movement (constitution v2.0.0 Principio X, spec 003 FR-010) — the
// InstallmentPayment row itself never stores a Movement reference, the link
// lives on the Movement side via `installment_payment_id`.
export interface InstallmentPayment extends BaseEntity {
  id: UUID;
  installment_loan_id: UUID;
  kind: InstallmentPaymentKind;
  amount: number; // in cents
  date: Date;
  adjustment_type?: InstallmentAdjustmentType; // only when kind = 'principal' (FR-016)
  resulting_value?: number; // the value the user typed in themselves — never calculated (FR-017); only when kind = 'principal'
}
